"""Measure each scene's light from its background and write utils/sceneLightTable.js (read by utils/sceneLight.js).

The light falling on the characters is taken from the band where they stand (canvas y 200-560):
  * hue: the band's mean colour normalised to full brightness, its departure from grey pushed by HUE_BOOST (an
    overcast scene's light is nearly grey, and grey times a sprite changes nothing), then mixed with white by STRENGTH;
  * dim: the band's brightness against a typical character's (~50 luma), never below DIM_MIN;
  * saturation: the band's against a typical character's (~0.45): under a grey sky the scene has lost its colour and
    the characters must lose some too (never below SAT_MIN; colourful interiors stay near 1).
Re-run after a background changes; a scene listed in OVERRIDE keeps hand-tuned values.

  python3 tools/artgen/scene_light.py
"""
import colorsys, os
from PIL import Image, ImageStat

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
STRENGTH, HUE_BOOST, CHAR_LUMA, DIM_MIN = 0.6, 1.8, 50.0, 0.8
CHAR_SAT, SAT_MIN = 0.45, 0.65

SCENES = {   # scene key -> its background (the base one where a scene has growth / decay variants)
    'EntryScene': 'EntryCity.png', 'CrossroadScene': 'crossroad.png', 'EggCatedralScene': 'egg-catedral.png',
    'CathedralEntrance': 'CathedralEntrance.png', 'ScraperScene': 'Scraper1140.png',
    'ScraperInteriorScene': 'Scraper_interior.png', 'ScraperAmbraScene': 'ScraperAmbra.png',
    'SkyshipBoardScene': 'skyship_board.png', 'Shed521GateScene': 'Shed521_gate.png', 'Shed521Scene': 'Shed521.png',
    'Shed521FloorsScene': 'Shed521_floors.png', 'ShedCourtyard': 'ShedMutationCourtyard.png',
    'ShedRegistrationScene': 'ShedRegistrationZone.png', 'ShedHallScene': 'ShedHall.png',
    'ShedApplicationsScene': 'ShedApplications.png', 'ShedAbandonedOfficeScene': 'ShedAbandonedOffice.png',
    'ScreamingCorkScene': 'ScreamingCork.png', 'ScreamingCorkInteriorScene': 'ScreamingCorkInterior.png',
    'ScreamingCorkClubScene': 'ScreamingCorkClub.png', 'VoxMarket': 'Voxmarket.png',
    'VoxmarketMarketScene': 'VoxmarketMarket.png', 'VoxmarketHallScene': 'VoxmarketHall.png',
    'BurningBearStreetScene': 'BurningBearStreet.png',
}
OVERRIDE = {}   # scene key -> (0xRRGGBB, saturation), when the measured light needs a hand


def light(bg):
    im = Image.open(os.path.join(REPO, 'assets/images/backgrounds', bg)).convert('RGB').crop((0, 200, 1067, 560))
    r, g, b = ImageStat.Stat(im).mean
    luma = 0.299 * r + 0.587 * g + 0.114 * b
    m = max(r, g, b)
    n = [c / m for c in (r, g, b)]
    mean = sum(n) / 3
    n = [max(0.0, mean + (c - mean) * HUE_BOOST) for c in n]
    n = [c / max(n) for c in n]
    dim = min(1.0, max(DIM_MIN, luma / CHAR_LUMA))
    tint = tuple(round((255 * (1 - STRENGTH) + c * 255 * STRENGTH) * dim) for c in n)
    px = list(im.resize((267, 90)).getdata())
    bg_sat = sum(colorsys.rgb_to_hsv(*(v / 255 for v in p))[1] for p in px) / len(px)
    sat = round(min(1.0, max(SAT_MIN, 0.35 + 0.65 * bg_sat / CHAR_SAT)), 2)
    return tint, sat


if __name__ == '__main__':
    rows = []
    for key, bg in SCENES.items():
        if key in OVERRIDE: rgb, sat = OVERRIDE[key]
        else:
            (r, g, b), sat = light(bg); rgb = (r << 16) | (g << 8) | b
        rows.append(f"    {key}: [0x{rgb:06x}, {sat}],   // {bg}")
    out = os.path.join(REPO, 'utils/sceneLightTable.js')
    with open(out, 'w') as f:
        f.write("// Generated by tools/artgen/scene_light.py: each scene's light on its characters, [colour, saturation].\n")
        f.write('export const SCENE_LIGHT = {\n' + '\n'.join(rows) + '\n};\n')
    print('\n'.join(rows))
