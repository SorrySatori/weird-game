// IntroScene — "The Myceliar Summons", the opening cutscene.
//
// Shot 1: the Hymnar, the cult's sacred giant mushroom (NOT the god — Obazoba has no body, he is an ideal). A tall
//         picture (1067×1000); the camera pans from the cap down to the temple at its foot while the narrator speaks.
//         A pulse of light runs in along a root (from the direction of the city) and the camera rides it up the stalk;
//         when it reaches the gills they flare and shed spores.
// Shot 2: the Council chamber of the Highest Humenium Council. The archpriests sit around a table holding a pool of
//         liquid mycelium; the camera cuts to a 2× close-up of whoever speaks (only their mouth moves while the line
//         types out; the others sit still and only now and then blink or breathe), the pool ripples, candles flicker,
//         the old elder at the end of the table sleeps and snores spores.
//
// Art is generated by tools/artgen/intro_*.py into assets/images/intro/ (Aseprite sources: assets/aseprite/Intro_*).
// Text: lang/*/intro.js (`intro.opening` captions, `intro.dialogues[]` with `who` = narrator|varhun|tynri|rhull).
// Advance with SPACE / ENTER / click (first press completes a line that is still typing); ESC skips the intro.

import LanguageSystem from '../systems/LanguageSystem.js';

const IMG = 'assets/images/intro/';
const OY = 1100;                                 // shot 2 lives below shot 1 in world space
const FONT = '"Courier New", monospace';
const INK = '#c8e6d0';
const NAME_COLOR = { narrator: '#8fb89a', varhun: '#c9a6e0', tynri: '#e8dcbc', rhull: '#a6d68e' };
const BACK_ROW = ['tynri', 'varhun', 'rhull'];
const FRAME = { back: [128, 176], end: [200, 350] };
const ELDER_R_BULB = { x: 154, y: 36 };          // glowing bulb of the right elder's crook, in its (unflipped) frame
const ELDER_L_CAP = { x: 190, y: 72 };           // edge of the sleeping elder's cap, where the snore-spores puff out
const TYPE_MS = 26;
// idle frames of the seated figures (see idleLife): back row 0 rest, 1 inhale, 2 blink, 3 eye-glow; elder_r 3 = blink
const BACK_LIFE = { min: 3500, max: 9500, breath: 1, blink: 2, glow: 3 };
const ELDER_LIFE = { min: 4500, max: 10000, breath: 1, blink: 3, glow: 2 };

class IntroScene extends Phaser.Scene {
    constructor() {
        super({ key: 'IntroScene' });
    }

    preload() {
        this.load.image('introHymnar', IMG + 'hymnar.png');
        this.load.image('introHymnarGills', IMG + 'hymnar_gills.png');
        this.load.image('introHymnarGlow', IMG + 'hymnar_glow.png');
        this.load.json('introHymnarData', IMG + 'hymnar.json');
        this.load.image('introCouncilBg', IMG + 'council_bg.png');
        this.load.image('introCouncilTable', IMG + 'council_table.png');
        this.load.image('introCouncilGlow', IMG + 'council_glow.png');
        this.load.json('introCouncilData', IMG + 'council.json');
        for (const who of BACK_ROW) {
            this.load.spritesheet(`intro_${who}`, IMG + `council_${who}.png`, { frameWidth: FRAME.back[0], frameHeight: FRAME.back[1] });
        }
        for (const who of ['elder_l', 'elder_r']) {
            this.load.spritesheet(`intro_${who}`, IMG + `council_${who}.png`, { frameWidth: FRAME.end[0], frameHeight: FRAME.end[1] });
        }
        this.load.audio('introMusic', 'assets/sounds/obazoba-hall.mp3');
    }

    create() {
        // scene instances are re-used: reset per-run state
        this.lang = LanguageSystem.getInstance();
        this.busy = false;
        this.ending = false;
        this.signalRunning = false;
        this.typing = null;
        this.typingFull = null;
        this.shot = 1;
        this.step = -1;
        this.lineIndex = 0;
        this.speakers = {};
        this.W = this.scale.width;
        this.H = this.scale.height;

        this.makeTextures();

        const cam = this.cameras.main;
        cam.setBackgroundColor('#000000');
        cam.setRoundPixels(true);
        this.uiCam = this.cameras.add(0, 0, this.W, this.H);
        this.uiObjects = [];
        this.worldObjects = [];

        this.buildShot1();
        this.buildShot2();
        this.buildUI();
        this.cameras.main.ignore(this.uiObjects);
        this.uiCam.ignore(this.worldObjects);

        const opening = this.lang.t('intro.opening');
        const dialogues = this.lang.t('intro.dialogues');
        this.dialogues = Array.isArray(dialogues) ? dialogues.map((d) => ({ ...d, who: d.who || this.guessWho(d.speaker) })) : [];
        // narration that belongs over the Hymnar: the captions + any leading narrator lines of the dialogue
        const lead = [];
        while (this.dialogues.length && this.dialogues[0].who === 'narrator') lead.push(this.dialogues.shift());
        this.shot1Steps = this.makeShot1Steps(Array.isArray(opening) ? opening : [], lead);

        this.input.keyboard.on('keydown-SPACE', () => this.advance());
        this.input.keyboard.on('keydown-ENTER', () => this.advance());
        this.input.keyboard.on('keydown-ESC', () => this.skip());
        this.input.on('pointerdown', () => this.advance());

        this.sound.stopAll();
        this.sceneMusic = this.sound.add('introMusic', { loop: true, volume: 0 });
        this.sceneMusic.play();
        this.tweens.add({ targets: this.sceneMusic, volume: 0.8, duration: 4000 });

        this.startShot1();
    }

    // ------------------------------------------------------------------ setup helpers
    makeTextures() {
        if (!this.textures.exists('introSoftGlow')) {
            const t = this.textures.createCanvas('introSoftGlow', 64, 64);
            const ctx = t.getContext();
            const g = ctx.createRadialGradient(32, 32, 0, 32, 32, 32);
            g.addColorStop(0, 'rgba(255,255,255,1)');
            g.addColorStop(0.35, 'rgba(255,255,255,0.45)');
            g.addColorStop(1, 'rgba(255,255,255,0)');
            ctx.fillStyle = g;
            ctx.fillRect(0, 0, 64, 64);
            t.refresh();
        }
        if (!this.textures.exists('introSpore')) {
            const g = this.make.graphics({ x: 0, y: 0, add: false });
            g.fillStyle(0xffffff, 1).fillRect(0, 0, 2, 2);
            g.generateTexture('introSpore', 2, 2);
            g.destroy();
        }
    }

    /**
     * Plays [[frame, ms], ...] on a sprite with exact per-frame timing (Phaser's own per-frame `duration` is only
     * honoured without a frame rate, so the council's slow motions are sequenced here). onFrame(frame) on each step.
     */
    playSeq(spr, seq, loop = true, onFrame = null) {
        this.stopSeq(spr);
        let i = 0;
        const step = () => {
            const [frame, ms] = seq[i];
            spr.setFrame(frame);
            onFrame?.(frame);
            i = (i + 1) % seq.length;
            if (i === 0 && !loop) { spr._seq = null; return; }
            spr._seq = this.time.delayedCall(ms, step);
        };
        step();
    }

    stopSeq(spr) {
        spr._seq?.remove(false);
        spr._seq = null;
    }

    /** an unhurried, slightly irregular mouth: frames 4-6 open by degrees, 7 = closed pause */
    talkSeq() {
        const seq = [];
        let prev = -1;
        for (let i = 0; i < 18; i++) {
            if (i % 6 === 5) { seq.push([7, Phaser.Math.Between(240, 380)]); prev = 7; continue; }
            let f;
            do { f = Phaser.Math.Between(4, 6); } while (f === prev);
            seq.push([f, Phaser.Math.Between(150, 230)]);
            prev = f;
        }
        return seq;
    }

    world(obj) { this.worldObjects.push(obj); return obj; }
    ui(obj) { this.uiObjects.push(obj); return obj; }

    guessWho(speaker = '') {
        const s = speaker.toUpperCase();
        if (s.includes('VARHUN')) return 'varhun';
        if (s.includes('TYNRI')) return 'tynri';
        if (s.includes('RHULL')) return 'rhull';
        return 'narrator';
    }

    // ------------------------------------------------------------------ shot 1: the Hymnar
    buildShot1() {
        const d = this.cache.json.get('introHymnarData') || {};
        this.hymnarData = d;
        this.world(this.add.image(0, 0, 'introHymnar').setOrigin(0, 0).setDepth(0));
        this.gills = this.world(this.add.image(0, 0, 'introHymnarGills').setOrigin(0, 0).setDepth(1)
            .setBlendMode(Phaser.BlendModes.ADD).setAlpha(0.2));
        this.obGlow = this.world(this.add.image(0, 0, 'introHymnarGlow').setOrigin(0, 0).setDepth(2)
            .setBlendMode(Phaser.BlendModes.ADD).setAlpha(0.25));
        this.tweens.add({ targets: this.obGlow, alpha: 0.5, duration: 2600, yoyo: true, repeat: -1, ease: 'Sine.easeInOut' });
        this.tweens.add({ targets: this.gills, alpha: 0.32, duration: 3400, yoyo: true, repeat: -1, ease: 'Sine.easeInOut' });

        // pilgrims' lanterns on the walkway, the prayer ropes and in the stone priests' hands
        for (const l of d.lanterns || []) {
            const g = this.world(this.add.image(l.x, l.y, 'introSoftGlow').setDepth(2).setBlendMode(Phaser.BlendModes.ADD)
                .setTint(0xe0b050).setScale(l.r / 32).setAlpha(0.45));
            this.tweens.add({
                targets: g, alpha: { from: 0.3, to: 0.6 }, duration: 900 + Math.random() * 1400, yoyo: true, repeat: -1,
                ease: 'Sine.easeInOut', delay: Math.random() * 1500,
            });
        }

        // spores sifting down from the gills, and a few motes adrift in the cavern
        const rimY = d.rimY || 330;
        this.sporeFall = this.world(this.add.particles(0, 0, 'introSpore', {
            emitZone: { type: 'random', source: new Phaser.Geom.Rectangle(0, rimY, this.W, 70) },
            lifespan: 9000, speedY: { min: 6, max: 22 }, speedX: { min: -6, max: 6 },
            alpha: { start: 0.9, end: 0 }, tint: [0xa3eaa3, 0xd4ffd2, 0x74cc7f], frequency: 70, quantity: 1,
            blendMode: 'ADD',
        }).setDepth(3));
        this.world(this.add.particles(0, 0, 'introSpore', {
            emitZone: { type: 'random', source: new Phaser.Geom.Rectangle(0, 0, this.W, 1000) },
            lifespan: 6000, speedY: { min: -6, max: 6 }, speedX: { min: -8, max: 8 },
            alpha: { start: 0, end: 0.6, ease: 'Sine.easeInOut' }, scale: { min: 0.5, max: 1 },
            tint: 0x74cc7f, frequency: 160, blendMode: 'ADD',
        }).setDepth(3));

        // drips falling from the rotting half of the cap
        const drips = d.drips || [];
        if (drips.length) {
            this.dripTimer = this.time.addEvent({
                delay: 900, loop: true, callback: () => {
                    const p = Phaser.Utils.Array.GetRandom(drips);
                    const drop = this.world(this.add.rectangle(p.x, p.y + 2, 2, 3, 0x834028).setDepth(3));
                    this.uiCam.ignore(drop);
                    this.tweens.add({ targets: drop, y: p.y + 160 + Math.random() * 120, alpha: 0, duration: 1600, ease: 'Quad.easeIn', onComplete: () => drop.destroy() });
                },
            });
        }

        // the signal: a mote of light that runs the length of the vein
        const pts = d.signal || [];
        if (pts.length > 1) {
            this.signalPath = new Phaser.Curves.Path(pts[0][0], pts[0][1]);
            for (let i = 1; i < pts.length; i++) this.signalPath.lineTo(pts[i][0], pts[i][1]);
        }
        this.pulse = this.world(this.add.image(-100, -100, 'introSoftGlow').setDepth(4).setBlendMode(Phaser.BlendModes.ADD)
            .setTint(0xa3eaa3).setScale(0.55).setVisible(false));
        this.pulseTrail = this.world(this.add.particles(0, 0, 'introSpore', {
            lifespan: 700, speed: { min: 4, max: 18 }, alpha: { start: 1, end: 0 }, scale: { start: 1.5, end: 0.5 },
            tint: [0xd4ffd2, 0x74cc7f], frequency: 18, blendMode: 'ADD', emitting: false,
        }).setDepth(4));
        this.pulseTrail.startFollow(this.pulse);
    }

    /**
     * The choreography of shot 1: down the cap, down the stalk to the temple at its foot, then the signal arrives
     * along a root and the camera rides it up the stalk to the gills, and finally back down to the temple.
     */
    makeShot1Steps(captions, lead) {
        const steps = [];
        const plan = [
            { scroll: 110, dur: 7000, pos: 'bottom' },
            { scroll: 400, dur: 9000, pos: 'top' },
            { signal: true, pos: 'bottom' },
        ];
        captions.forEach((text, i) => steps.push({ text, ...(plan[i] || { scroll: 400, dur: 5000, pos: 'top' }) }));
        lead.forEach((line) => steps.push({ text: line.text, speaker: line.speaker, scroll: 400, dur: 6000, pos: 'top' }));
        if (!steps.length) steps.push({ text: '', scroll: 400, dur: 4000 });
        return steps;
    }

    startShot1() {
        const cam = this.cameras.main;
        cam.setBounds(0, 0, this.W, 1000);
        cam.setZoom(1);
        cam.setScroll(0, 0);
        this.fadeFrom(2200);
        this.time.delayedCall(900, () => this.nextShot1Step());
    }

    nextShot1Step() {
        this.step++;
        const st = this.shot1Steps[this.step];
        if (!st) { this.toShot2(); return; }
        const cam = this.cameras.main;
        if (this.panTween) this.panTween.stop();
        if (st.signal) {
            this.hideCaption();
            this.nextMark.setAlpha(0);
            this.runSignal(() => this.showCaption(st.text, st.speaker, st.pos));
            return;
        }
        this.panTween = this.tweens.add({ targets: cam, scrollY: st.scroll, duration: st.dur, ease: 'Sine.easeInOut' });
        this.showCaption(st.text, st.speaker, st.pos);
    }

    /** a mote of light runs in along the root and up the stalk; the camera rides along with it */
    runSignal(onArrive) {
        if (!this.signalPath) { onArrive(); return; }
        this.signalRunning = true;
        const cam = this.cameras.main;
        const v = new Phaser.Math.Vector2();
        const c = { t: 0 };
        this.pulse.setVisible(true);
        this.pulseTrail.start();
        this.tweens.add({ targets: this.obGlow, alpha: 0.85, duration: 2600, yoyo: true, ease: 'Sine.easeInOut' });
        this.signalTween = this.tweens.add({
            targets: c, t: 1, duration: 5600, ease: 'Sine.easeInOut',
            onUpdate: () => {
                this.signalPath.getPoint(c.t, v);
                this.pulse.setPosition(v.x, v.y);
                const target = Phaser.Math.Clamp(v.y - 330, 0, 400);
                cam.scrollY += (target - cam.scrollY) * 0.06;
            },
            onComplete: () => {
                this.signalRunning = false;
                this.pulse.setVisible(false);
                this.pulseTrail.stop();
                this.flareGills();
                onArrive();
            },
        });
    }

    flareGills() {
        this.tweens.killTweensOf(this.gills);
        this.gills.setAlpha(1);
        this.tweens.add({ targets: this.gills, alpha: 0.3, duration: 3200, ease: 'Sine.easeOut' });
        this.cameras.main.shake(500, 0.0025);
        const rimY = this.hymnarData.rimY || 330;
        const burst = this.world(this.add.particles(0, 0, 'introSpore', {
            emitZone: { type: 'random', source: new Phaser.Geom.Rectangle(0, rimY, this.W, 60) },
            lifespan: 5000, speedY: { min: 20, max: 70 }, speedX: { min: -14, max: 14 },
            alpha: { start: 1, end: 0 }, scale: { min: 1, max: 2 }, tint: [0xd4ffd2, 0xa3eaa3, 0xf4fff2],
            blendMode: 'ADD', emitting: false,
        }).setDepth(3));
        this.uiCam.ignore(burst);
        burst.explode(260);
        this.time.delayedCall(6000, () => burst.destroy());
    }

    // ------------------------------------------------------------------ shot 2: the Council chamber
    buildShot2() {
        const d = this.cache.json.get('introCouncilData') || { seats: {}, candles: [], glows: [], pool: { x: 533, y: 447, rx: 222, ry: 42 } };
        this.councilData = d;
        this.world(this.add.image(0, OY, 'introCouncilBg').setOrigin(0, 0).setDepth(0));
        this.world(this.add.image(0, OY, 'introCouncilTable').setOrigin(0, 0).setDepth(2));
        this.councilGlow = this.world(this.add.image(0, OY, 'introCouncilGlow').setOrigin(0, 0).setDepth(3)
            .setBlendMode(Phaser.BlendModes.ADD).setAlpha(0.25));
        this.tweens.add({ targets: this.councilGlow, alpha: 0.45, duration: 2800, yoyo: true, repeat: -1, ease: 'Sine.easeInOut' });

        // the archpriests (back row: cut at the table's far edge, hands on the table) + the elders at the ends
        for (const who of BACK_ROW) {
            const s = d.seats[who];
            if (!s) continue;
            const spr = this.world(this.add.sprite(s.x, OY + s.y, `intro_${who}`, 0).setOrigin(0.5, 1).setDepth(4));
            this.speakers[who] = spr;
            this.idleLife(spr, BACK_LIFE);
        }
        const el = d.seats.elder_l, er = d.seats.elder_r;
        if (el) {
            this.elderL = this.world(this.add.sprite(el.x, OY + el.y, 'intro_elder_l', 0).setOrigin(0.5, 1).setDepth(5));
            // the sleeping elder breathes slowly; his head sinks on the out-breath
        }
        if (er) {
            this.elderR = this.world(this.add.sprite(er.x, OY + er.y, 'intro_elder_r', 0).setOrigin(0.5, 1).setDepth(5).setFlipX(true));
            this.idleLife(this.elderR, ELDER_LIFE);
            const bx = er.x + FRAME.end[0] / 2 - 1 - ELDER_R_BULB.x, by = OY + er.y - FRAME.end[1] + ELDER_R_BULB.y;
            const bulb = this.world(this.add.image(bx, by + 2, 'introSoftGlow').setDepth(6).setBlendMode(Phaser.BlendModes.ADD)
                .setTint(0x74cc7f).setScale(0.9).setAlpha(0.5));
            this.tweens.add({ targets: bulb, alpha: 0.8, scale: 1.05, duration: 1700, yoyo: true, repeat: -1, ease: 'Sine.easeInOut' });
        }

        // candle flames + glowing droplets / niches
        for (const c of d.candles || []) {
            const g = this.world(this.add.image(c.x, OY + c.y, 'introSoftGlow').setDepth(6).setBlendMode(Phaser.BlendModes.ADD)
                .setTint(0xe0b050).setScale(0.45).setAlpha(0.55));
            this.tweens.add({
                targets: g, alpha: { from: 0.35, to: 0.7 }, scale: { from: 0.4, to: 0.52 },
                duration: 140 + Math.random() * 220, yoyo: true, repeat: -1, ease: 'Stepped', easeParams: [3],
                delay: Math.random() * 300,
            });
        }
        for (const p of d.glows || []) {
            const g = this.world(this.add.image(p.x, OY + p.y, 'introSoftGlow').setDepth(1).setBlendMode(Phaser.BlendModes.ADD)
                .setTint(0x74cc7f).setScale(p.r / 32).setAlpha(0.25));
            this.tweens.add({ targets: g, alpha: 0.55, duration: 1800 + Math.random() * 1600, yoyo: true, repeat: -1, ease: 'Sine.easeInOut', delay: Math.random() * 2000 });
        }

        // spores rising off the pool
        const pool = d.pool;
        this.world(this.add.particles(0, 0, 'introSpore', {
            emitZone: { type: 'random', source: new Phaser.Geom.Ellipse(pool.x, OY + pool.y, pool.rx * 1.6, pool.ry * 1.4) },
            lifespan: 4200, speedY: { min: -26, max: -8 }, speedX: { min: -5, max: 5 },
            alpha: { start: 0.9, end: 0 }, tint: [0xa3eaa3, 0xd4ffd2], frequency: 90, blendMode: 'ADD',
        }).setDepth(3));
        this.ripples = this.world(this.add.graphics().setDepth(3).setBlendMode(Phaser.BlendModes.ADD));
        this.rippleList = [];

        // the old elder snores spores
        if (this.elderL) {
            const sx = el.x - FRAME.end[0] / 2 + ELDER_L_CAP.x, sy = OY + el.y - FRAME.end[1] + ELDER_L_CAP.y;
            this.snore = this.world(this.add.particles(sx, sy, 'introSpore', {
                lifespan: 2600, speedX: { min: 4, max: 16 }, speedY: { min: -14, max: -4 },
                alpha: { start: 0.8, end: 0 }, scale: { start: 1, end: 2 }, tint: [0xd6c897, 0xa3eaa3], emitting: false,
            }).setDepth(6));
            // he breathes slowly; on each out-breath (frame 2) his head sinks and a puff of spores escapes
            this.playSeq(this.elderL, [[0, 2600], [1, 2100], [0, 1500], [2, 2600]], true, (f) => { if (f === 2) this.snore.explode(8); });
        }
    }

    toShot2() {
        this.busy = true;
        this.hideCaption();
        this.fadeTo(1100, () => {
            this.shot = 2;
            if (this.panTween) this.panTween.stop();
            this.sporeFall.stop();
            const cam = this.cameras.main;
            cam.setBounds(0, OY, this.W, this.H);
            cam.setZoom(1);
            cam.centerOn(this.W / 2, OY + this.H / 2);
            this.fadeFrom(1300);
            this.time.delayedCall(1000, () => { this.busy = false; this.nextLine(); });
        });
    }

    nextLine() {
        const line = this.dialogues[this.lineIndex++];
        if (!line) { this.finale(); return; }
        const who = line.who;
        for (const [k, spr] of Object.entries(this.speakers)) this.shade(spr, k === who || who === 'narrator' ? 255 : 182);
        this.frameSpeaker(who);
        this.rippleTo(who);
        this.showDialogLine(line);
    }

    /** close-up (2×) on the speaker; the narrator gets the wide shot */
    frameSpeaker(who) {
        const cam = this.cameras.main;
        const s = this.councilData.seats[who];
        if (!s || who === 'narrator') {
            cam.zoomTo(1, 900, 'Sine.easeInOut');
            cam.pan(this.W / 2, OY + this.H / 2, 900, 'Sine.easeInOut');
            return;
        }
        const tx = s.x, ty = OY + s.y - 72;
        const first = cam.zoom < 1.5;
        cam.zoomTo(2, first ? 1100 : 700, 'Sine.easeInOut', true);
        cam.pan(tx, ty, first ? 1100 : 700, 'Sine.easeInOut', true);
    }

    /**
     * Keeps a seated figure alive without fidgeting: it holds still for several seconds, then does one slow, small
     * thing (a blink, a breath, a glint of the eye) and goes still again. Figures are not synchronised.
     */
    idleLife(spr, life) {
        spr._life?.remove(false);
        if (spr._talking) return;
        spr._life = this.time.delayedCall(Phaser.Math.Between(life.min, life.max), () => {
            if (spr._talking) return;
            const r = Math.random();
            const [frame, hold] = r < 0.55 ? [life.blink, 150] : r < 0.85 ? [life.breath, 1700] : [life.glow, 1400];
            spr.setFrame(frame);
            spr._life = this.time.delayedCall(hold, () => {
                if (!spr._talking) spr.setFrame(0);
                this.idleLife(spr, life);
            });
        });
    }

    /** fade a figure's brightness (focus on the speaker) instead of snapping the tint */
    shade(spr, to) {
        spr._shadeTween?.stop();
        const from = spr._shadeLevel ?? 255;
        if (from === to) return;
        spr._shadeTween = this.tweens.addCounter({
            from, to, duration: 600, ease: 'Sine.easeInOut',
            onUpdate: (tw) => {
                const v = Math.round(tw.getValue());
                spr._shadeLevel = v;
                spr.setTint(Phaser.Display.Color.GetColor(v, v, v));
            },
        });
    }

    rippleTo(who) {
        const pool = this.councilData.pool;
        this.tweens.killTweensOf(this.councilGlow);
        this.councilGlow.setAlpha(0.75);
        this.tweens.add({ targets: this.councilGlow, alpha: 0.3, duration: 1600, ease: 'Sine.easeOut',
            onComplete: () => this.tweens.add({ targets: this.councilGlow, alpha: 0.45, duration: 2800, yoyo: true, repeat: -1, ease: 'Sine.easeInOut' }) });
        const s = this.councilData.seats[who];
        const ox = s ? Phaser.Math.Linear(pool.x, s.x, 0.25) : pool.x;
        const r = { k: 0, x: ox, y: OY + pool.y };
        this.rippleList.push(r);
        this.tweens.add({ targets: r, k: 1, duration: 1800, ease: 'Sine.easeOut', onComplete: () => Phaser.Utils.Array.Remove(this.rippleList, r) });
    }

    update() {
        if (!this.ripples) return;
        this.ripples.clear();
        const pool = this.councilData?.pool;
        if (!pool) return;
        for (const r of this.rippleList) {
            const a = (1 - r.k) * 0.8;
            this.ripples.lineStyle(1, 0xa3eaa3, a);
            this.ripples.strokeEllipse(r.x, r.y, 30 + r.k * pool.rx * 1.7, 6 + r.k * pool.ry * 1.6);
            if (r.k > 0.25) {
                this.ripples.lineStyle(1, 0x74cc7f, a * 0.6);
                this.ripples.strokeEllipse(r.x, r.y, (r.k - 0.25) * pool.rx * 2.2, (r.k - 0.25) * pool.ry * 2.1);
            }
        }
    }

    finale() {
        this.busy = true;
        this.hideDialog();
        const cam = this.cameras.main;
        cam.zoomTo(1, 1600, 'Sine.easeInOut');
        cam.pan(this.W / 2, OY + this.H / 2, 1600, 'Sine.easeInOut');
        for (const spr of Object.values(this.speakers)) this.shade(spr, 255);
        this.tweens.killTweensOf(this.councilGlow);
        this.tweens.add({ targets: this.councilGlow, alpha: 1, duration: 1400, ease: 'Sine.easeIn' });
        const pool = this.councilData.pool;
        const rise = this.world(this.add.particles(0, 0, 'introSpore', {
            emitZone: { type: 'random', source: new Phaser.Geom.Ellipse(pool.x, OY + pool.y, pool.rx * 1.8, pool.ry * 1.6) },
            lifespan: 2600, speedY: { min: -90, max: -30 }, speedX: { min: -10, max: 10 }, scale: { min: 1, max: 2 },
            alpha: { start: 1, end: 0 }, tint: [0xd4ffd2, 0xa3eaa3, 0xf4fff2], frequency: 8, quantity: 3, blendMode: 'ADD',
        }).setDepth(7));
        this.uiCam.ignore(rise);
        this.time.delayedCall(1700, () => this.fadeTo(1500, () => this.endIntro()));
    }

    skip() {
        if (this.ending) return;
        this.busy = true;
        this.fadeTo(500, () => this.endIntro());
    }

    endIntro() {
        if (this.ending) return;
        this.ending = true;
        this.tweens.add({ targets: this.sceneMusic, volume: 0, duration: 400 });
        this.time.delayedCall(420, () => {
            this.sceneMusic?.stop();
            this.ending = false;
            this.scene.start('TransitionScene');
        });
    }

    // ------------------------------------------------------------------ UI: captions, dialog panel, fades
    buildUI() {
        const W = this.W, H = this.H;
        // shot 1: cinematic caption over a soft dark band
        this.captionBand = this.ui(this.add.rectangle(W / 2, H - 70, W, 140, 0x000000, 0.55).setDepth(100).setAlpha(0));
        this.captionText = this.ui(this.add.text(W / 2, H - 70, '', {
            fontFamily: FONT, fontSize: '19px', fill: INK, align: 'center', wordWrap: { width: W - 220 }, lineSpacing: 8,
        }).setOrigin(0.5).setDepth(101));
        this.captionName = this.ui(this.add.text(W / 2, H - 124, '', {
            fontFamily: FONT, fontSize: '14px', fill: NAME_COLOR.narrator, fontStyle: 'bold',
        }).setOrigin(0.5).setDepth(101));

        // shot 2: dialog panel in the game's chronicle colours
        const pw = W - 80, ph = 116, py = H - ph / 2 - 14;
        this.panel = this.ui(this.add.rectangle(W / 2, py, pw, ph, 0x0c1410, 0.92).setStrokeStyle(2, 0x2f5a44).setDepth(100).setAlpha(0));
        this.panelName = this.ui(this.add.text(W / 2 - pw / 2 + 22, py - ph / 2 + 12, '', {
            fontFamily: FONT, fontSize: '17px', fill: NAME_COLOR.narrator, fontStyle: 'bold',
        }).setDepth(101).setAlpha(0));
        this.panelText = this.ui(this.add.text(W / 2 - pw / 2 + 22, py - ph / 2 + 40, '', {
            fontFamily: FONT, fontSize: '17px', fill: INK, wordWrap: { width: pw - 70 }, lineSpacing: 6,
        }).setDepth(101).setAlpha(0));
        this.nextMark = this.ui(this.add.text(W / 2 + pw / 2 - 22, py + ph / 2 - 10, '▼', {
            fontFamily: FONT, fontSize: '14px', fill: '#7fff8e',
        }).setOrigin(1, 1).setDepth(101).setAlpha(0));
        this.tweens.add({ targets: this.nextMark, y: '+=3', duration: 500, yoyo: true, repeat: -1, ease: 'Sine.easeInOut' });

        this.skipHint = this.ui(this.add.text(W - 14, 12, this.lang.t('intro.skipHint'), {
            fontFamily: FONT, fontSize: '12px', fill: '#5f7a68',
        }).setOrigin(1, 0).setDepth(101).setAlpha(0.8));
        this.fader = this.ui(this.add.rectangle(W / 2, H / 2, W, H, 0x000000, 1).setDepth(200));
    }

    fadeFrom(ms) {
        this.tweens.killTweensOf(this.fader);
        this.fader.setAlpha(1);
        this.tweens.add({ targets: this.fader, alpha: 0, duration: ms, ease: 'Sine.easeOut' });
    }

    fadeTo(ms, done) {
        this.tweens.killTweensOf(this.fader);
        this.tweens.add({ targets: this.fader, alpha: 1, duration: ms, ease: 'Sine.easeIn', onComplete: done });
    }

    typeInto(textObj, full, onDone) {
        if (this.typing) this.typing.remove(false);
        textObj.setText('');
        this.nextMark.setAlpha(0);
        if (!full) { this.typing = null; onDone?.(); return; }
        let i = 0;
        this.typingFull = { textObj, full, onDone };
        this.typing = this.time.addEvent({
            delay: TYPE_MS, repeat: full.length - 1, callback: () => {
                i++;
                textObj.setText(full.slice(0, i));
                if (i >= full.length) this.finishTyping();
            },
        });
    }

    finishTyping() {
        if (!this.typingFull) return;
        const { textObj, full, onDone } = this.typingFull;
        this.typingFull = null;
        if (this.typing) { this.typing.remove(false); this.typing = null; }
        textObj.setText(full);
        onDone?.();
    }

    showCaption(text, speaker, pos = 'bottom') {
        const y = pos === 'top' ? 76 : this.H - 70;
        this.captionBand.setY(y);
        this.captionText.setY(y);
        this.captionName.setY(y - 54);
        this.tweens.add({ targets: this.captionBand, alpha: 1, duration: 600 });
        this.captionName.setText(speaker || '');
        this.typeInto(this.captionText, text, () => this.nextMark.setAlpha(1));
    }

    hideCaption() {
        this.captionText.setText('');
        this.captionName.setText('');
        this.tweens.add({ targets: this.captionBand, alpha: 0, duration: 400 });
    }

    showDialogLine(line) {
        this.hideCaption();
        [this.panel, this.panelName, this.panelText].forEach((o) => o.setAlpha(1));
        this.panelName.setText(line.speaker || '').setColor(NAME_COLOR[line.who] || NAME_COLOR.narrator);
        this.panelText.setFontStyle(line.who === 'narrator' ? 'italic' : 'normal');
        const spr = this.speakers[line.who];
        if (spr) {
            spr._talking = true;
            spr._life?.remove(false);
            this.playSeq(spr, this.talkSeq());
        }
        this.typeInto(this.panelText, line.text, () => {
            if (spr) {
                this.stopSeq(spr);
                spr.setFrame(0);
                spr._talking = false;
                this.idleLife(spr, BACK_LIFE);
            }
            this.nextMark.setAlpha(1);
        });
    }

    hideDialog() {
        [this.panel, this.panelName, this.panelText, this.nextMark].forEach((o) => this.tweens.add({ targets: o, alpha: 0, duration: 400 }));
    }

    advance() {
        if (this.busy || this.ending) return;
        if (this.typingFull) { this.finishTyping(); return; }
        if (this.shot === 1) {
            if (this.signalRunning) return;
            this.nextShot1Step();
        } else {
            this.nextLine();
        }
    }
}

export default IntroScene;
